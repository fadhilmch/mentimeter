import { chromium } from '@playwright/test'
const base = 'http://localhost:3199'
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] })
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } })
const p = await ctx.newPage()
p.on('console', (m) => console.log('[console]', m.type(), m.text().slice(0, 200)))
p.on('pageerror', (e) => console.log('[pageerror]', String(e).slice(0, 300)))
ctx.on('page', (pg) => console.log('[popup]', pg.url()))
await p.goto(base + '/login', { waitUntil: 'networkidle' })
const [popup] = await Promise.all([ctx.waitForEvent('page'), p.getByRole('button', { name: 'Continue with Google' }).click()])
await popup.waitForLoadState()
await popup.getByText('Add new account').click()
await popup.locator('#email-input').fill('grace2@example.com')
await popup.locator('#display-name-input').fill('Grace Two')
await popup.getByRole('button', { name: 'Sign in with Google.com' }).click()
await p.waitForTimeout(8000)
console.log('main url:', p.url())
console.log('banner:', await p.locator('.error-banner').textContent().catch(() => 'none'))
await browser.close()
